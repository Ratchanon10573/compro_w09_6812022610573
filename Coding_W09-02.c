#include <stdio.h>

int main() {

    int sum, p, x, y;
    sum = 0;
    for (x = 1, y = 1; x * y <= 15; x++, y+= 2) 
    {
        p = x * y;
        sum += p;
        printf("%d * %d = %d\n", x, y, p);
    }
    printf("summation of x * y = %d\n", sum);
    return 0;
}
/*
1. ประกาศตัวแปร:
   - int sum, p, x, y;: ประกาศตัวแปร sum สำหรับเก็บผลรวม, p สำหรับเก็บผลคูณ, x และ y สำหรับใช้ในลูป
   - sum = 0;: กำหนดค่าเริ่มต้นของ sum เป็น 0 เพื่อเริ่มการสะสมผลรวม
2. ลูป for:
   - for (x = 1, y = 1; x * y <= 15; x++, y+= 2):
     - x จะเพิ่มขึ้นทีละ 1 (x++)
     - y จะเพิ่มขึ้นทีละ 2 (y += 2) 
3. ภายในลูป:
   - p = x * y;: คำนวณผลคูณของ x และ y แล้วเก็บไว้ในตัวแปร p
   - sum += p;: เพิ่มค่าของ p ลงใน sum เพื่อสะสมผลรวม
   - printf("%d * %d = %d\n", x, y, p);: แสดงผลลัพธ์ของการคูณในรูปแบบ "x * y = p" ในแต่ละรอบของลูป
4. หลังจากลูป:
   - printf("summation of x * y = %d\n", sum);: แสดงผลรวมของผลคูณทั้งหมดที่ได้จากลูป
5. การคืนค่าจากฟังก์ชัน main:
   - return 0;: คืนค่า 0 เพื่อบอกว่าการทำงานของโปรแกรมเสร็จสมบูรณ์
ค่าที่เปลี่ยนไปของตัวแปรในแต่ละรอบของลูป:
- รอบที่ 1: x = 1, y = 1, p = 1 * 1 = 1, sum = 0 + 1 = 1
- รอบที่ 2: x = 2, y = 3, p = 2 * 3 = 6, sum = 1 + 6 = 7
- รอบที่ 3: x = 3, y = 5, p = 3 * 5 = 15, sum = 7 + 15 = 22
- รอบที่ 4: x = 4, y = 7, p = 4 * 7 = 28 (ลูปหยุดเพราะ 28 > 15)
ผลลัพธ์ที่ได้จากการรันโปรแกรมจะเป็น:
1 * 1 = 1
2 * 3 = 6
3 * 5 = 15
summation of x * y = 22

สรุปและอภิปรายผลการทำงานของโปรแกรม:
- โปรแกรมสามารถวนลูปคำนวณผลคูณของ x และ y ทีละรอบได้ถูกต้อง
- เงื่อนไข x*y <= 15 ทำให้ลูปหยุดอัตโนมัติเมื่อค่าที่คูณกันเกิน 15
- ตัวแปร x และ y เพิ่มขึ้นตามรูปแบบที่กำหนด (x+1, y+2) ทุกครั้ง
- แสดงผลถูกต้องและได้ผลรวมของค่าที่คูณได้ทั้งหมดตามที่ตั้งไว้
*/