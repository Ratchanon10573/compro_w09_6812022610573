#include <stdio.h>

int main() {
    // กำหนดตัวแปร i เริ่มต้นที่ 1
    int i;

    // ใช้ลูป for เพื่อวนลูปจาก 1 ถึง 10
    for (i = 1; i <= 10; i++) { // เพิ่ม i ทีละ 1 ในแต่ละรอบ
        // ถ้า i เท่ากับ 6 
        if (i == 6) { 
            continue; // ข้ามการแสดงผลเมื่อ i เป็น 6
        }
        printf("%d ", i); // แสดงค่าของ i
    }
    
    return 0; // จบการทำงานของโปรแกรม
}